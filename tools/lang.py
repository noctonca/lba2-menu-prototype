#!/usr/bin/env python3
"""Writes src/lang_table.inc from lang/help.tsv: the voice texts in each Text language,
as CP850 bytes (the game font's code page). Run it after editing lang/help.tsv."""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
rows = []
for line in (root / "lang/help.tsv").read_text(encoding="utf-8").splitlines():
    if not line or line.startswith("#"):
        continue
    cols = line.split("\t")
    if len(cols) != 6:
        raise SystemExit(f"lang/help.tsv: want 6 columns, got {len(cols)}: {line!r}")
    rows.append(cols)


def c_string(text):
    out = []
    for b in text.encode("cp850"):
        if b == 0x22 or b == 0x5C:
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append(f'\\x{b:02x}""')  # end the escape so a following hex letter is not eaten
    return '"' + "".join(out) + '"'


lines = ["// Generated by tools/lang.py from lang/help.tsv; do not edit.\n"]
for cols in rows:
    lines.append("{" + ", ".join(c_string(c) for c in cols) + "},\n")
(root / "src/lang_table.inc").write_text("".join(lines), encoding="ascii")
print(f"{len(rows)} texts")
