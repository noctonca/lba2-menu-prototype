#!/usr/bin/env python3
"""Writes src/lang_help.inc from lang/help.tsv (the voice texts) and src/lang_menu.inc
from lang/menu.tsv (labels, values, titles, answers, legend words), each text in every
Text language as CP850 bytes (the game font's code page). Run it after editing either."""
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent


def read(name):
    rows, seen = [], set()
    for line in (root / "lang" / name).read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) != 6:
            raise SystemExit(f"lang/{name}: want 6 columns, got {len(cols)}: {line!r}")
        if cols[0] in seen:
            raise SystemExit(f"lang/{name}: {cols[0]!r} twice")
        seen.add(cols[0])
        rows.append(cols)
    return rows


def c_string(text):
    out = []
    for b in text.encode("cp850"):
        if b == 0x22 or b == 0x5C:
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append(f'\\x{b:02x}""')  # end the escape so a following hex letter is not eaten
    return '"' + "".join(out) + '"'


def write(name, out):
    rows = read(name)
    lines = [f"// Generated by tools/lang.py from lang/{name}; do not edit.\n"]
    for cols in rows:
        lines.append("{" + ", ".join(c_string(c) for c in cols) + "},\n")
    (root / "src" / out).write_text("".join(lines), encoding="ascii")
    print(f"lang/{name}: {len(rows)} texts")


write("help.tsv", "lang_help.inc")
write("menu.tsv", "lang_menu.inc")
